"""Local-filesystem storage backend."""

import os
import re
import shutil
import tempfile
from pathlib import Path
from typing import BinaryIO

from app.services.storage.base import (
    ORIGINALS,
    PREVIEWS,
    PROCESSED,
    InvalidStorageKeyError,
    StorageBackend,
    StorageObjectNotFoundError,
)

# Keys are server-generated: lowercase path segments of safe characters, '/'-separated.
_KEY_RE = re.compile(r"^[a-z0-9_-]+(/[a-z0-9._-]+)+$")


def validate_key(key: str) -> str:
    """Keys are server-generated; reject anything else (shared by every backend)."""
    if not _KEY_RE.fullmatch(key) or ".." in key.split("/"):
        raise InvalidStorageKeyError("Invalid storage key.")
    return key


class LocalStorage(StorageBackend):
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()
        for prefix in (ORIGINALS, PROCESSED, PREVIEWS):
            (self.root / prefix).mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        # Defence in depth: keys are generated by us, but never let one escape the root.
        path = (self.root / validate_key(key)).resolve()
        if not path.is_relative_to(self.root):
            raise InvalidStorageKeyError("Invalid storage key.")
        return path

    def save(self, key: str, data: BinaryIO) -> int:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temp file in the same directory, then rename: readers never see partial files.
        fd, tmp_name = tempfile.mkstemp(dir=path.parent, prefix=".upload-", suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as out:
                shutil.copyfileobj(data, out, length=64 * 1024)
                written = out.tell()
            os.replace(tmp_name, path)
        except BaseException:
            Path(tmp_name).unlink(missing_ok=True)
            raise
        return written

    def open(self, key: str) -> BinaryIO:
        try:
            return self._path(key).open("rb")
        except FileNotFoundError as exc:
            raise StorageObjectNotFoundError(key) from exc

    def delete(self, key: str) -> bool:
        try:
            self._path(key).unlink()
            return True
        except FileNotFoundError:
            return False

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()
